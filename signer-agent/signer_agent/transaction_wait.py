"""Wait on durable operations without ever allocating a replacement transaction."""
from contextlib import contextmanager
from contextvars import ContextVar
import json
import sys
import time
from requests.exceptions import ConnectionError as RequestsConnectionError, HTTPError, SSLError, Timeout
from web3.exceptions import (BadFunctionCallOutput, BlockNotFound, ContractLogicError,
                             ProviderConnectionError, TransactionNotFound)


def _transport_failure(error):
    if isinstance(error, SSLError):
        return False  # Certificate/authenticity failures require operator review.
    if isinstance(error, (RequestsConnectionError, Timeout, ProviderConnectionError)):
        return True
    return isinstance(error, HTTPError) and getattr(error.response, "status_code", None) in (429, 502, 503, 504)


def observation_pending(error):
    return (_transport_failure(error) or isinstance(error, (BlockNotFound, TransactionNotFound))
            or (type(error) is ValueError and str(error) in ("EVM_RECEIPT_HEAD_BEHIND", "EVM_RPC_BEHIND")))


def retry_observation(observe):
    """Recheck the same evidence after an inconsistent RPC read."""
    for attempt in range(3):
        try:
            return observe()
        except Exception as error:
            retry = (observation_pending(error)
                     or isinstance(error, (BadFunctionCallOutput, ContractLogicError))
                     or (type(error) is ValueError and str(error) in (
                         "BINDING_CHECK_FAILED", "CODE_HASH_MISMATCH", "BTC_CONTRACT_BUILD_MISMATCH",
                         "EVM_REORG_RECOVERY_REQUIRED")))
            if not retry or attempt == 2:
                raise
            time.sleep(0.5 * (attempt + 1))

_nonblocking = ContextVar("transaction_nonblocking", default=False)


@contextmanager
def nonblocking_transactions():
    token = _nonblocking.set(True)
    try:
        yield
    finally:
        _nonblocking.reset(token)


class TransactionPending(RuntimeError):
    def __init__(self, result):
        super().__init__("TRANSACTION_PENDING")
        self.result = dict(status="TRANSACTION_PENDING", **{
            key: result[key] for key in ("step", "tx_hash", "original_tx_hash", "reason") if key in result})
        from .participant_errors import participant_message
        self.result["message"] = participant_message(result.get("reason", "TRANSACTION_PENDING"))


class TransactionRecoveryRequired(RuntimeError):
    def __init__(self, result):
        super().__init__("RECOVERY_REQUIRED")
        self.result = dict(status="RECOVERY_REQUIRED", **{
            key: result[key] for key in ("step", "tx_hash", "reason") if key in result})
        from .participant_errors import participant_message
        self.result["message"] = participant_message(result.get("reason", "RECOVERY_REQUIRED"))


def apply_confirmed(runner, identity, *, timeout=86400, poll_interval=5):
    """A polling flow remains nonblocking; a direct command waits up to one day.

    Each retry uses the identical runner/profile/journal. The signed bytes and
    nonce are recovered by Bootstrap, never regenerated by a higher-level command.
    """
    if timeout < 0 or poll_interval <= 0:
        raise ValueError("TRANSACTION_WAIT_BOUNDS")
    deadline = time.monotonic() + timeout
    previous, last_pending = None, None
    while True:
        diagnostic = {}
        try:
            result = runner.apply(identity)
        except Exception as error:
            if _nonblocking.get() or last_pending is None or not _transport_failure(error):
                raise
            # A known pending operation keeps its exact runner/journal and
            # deadline. Never reinterpret semantic failures as availability.
            from .safe_errors import exception_code
            result = dict(last_pending, reason="RPC_UNAVAILABLE")
            diagnostic["error_code"] = exception_code(error)
            if isinstance(error, HTTPError):
                diagnostic["http_status"] = error.response.status_code
        if result["status"] == "RECOVERY_REQUIRED":
            raise TransactionRecoveryRequired(result)
        if result["status"] not in ("BROADCAST", "CONFIRMING") or _nonblocking.get():
            return result
        last_pending = result if result.get("tx_hash") else None
        public = dict(status="WAITING_FOR_TRANSACTION", **{
            key: result[key] for key in ("step", "tx_hash", "original_tx_hash", "reason") if key in result}, **diagnostic)
        if "reason" in public:
            from .participant_errors import participant_message
            public["message"] = participant_message(public["reason"])
        if public != previous:
            print(json.dumps(public, sort_keys=True), file=sys.stderr, flush=True)
            previous = public
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise TransactionPending(result)
        time.sleep(min(poll_interval, remaining))
