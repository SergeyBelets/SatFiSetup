#!/usr/bin/env python3
"""Test-only integer vectors for retained Bitcoin Core arithmetic equations.

This generator is neither a header verifier nor production consensus code.
GetCompact is compared independently with pinned rust-bitcoin in the Rust tests.
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def compact(target):
    size = (target.bit_length() + 7) // 8
    value = (target << (8 * (3 - size)) if size <= 3
             else target >> (8 * (size - 3)))
    if value & 0x00800000:
        value >>= 8
        size += 1
    return value | (size << 24)


def target(bits):
    size, word = bits >> 24, bits & 0x007fffff
    return word >> (8 * (3 - size)) if size <= 3 else word << (8 * (size - 3))


def main():
    values = {0, (1 << 256) - 1, target(0x1d00ffff), target(0x1702c070)}
    for bit in range(256):
        for delta in (-1, 0, 1):
            values.add((1 << bit) + delta)
    for index in range(64):
        values.add(int.from_bytes(hashlib.sha256(f"arithmetic-vector-{index}".encode()).digest(), "big"))
    rows = ["// Generated by generate_vectors.py; exact Python integers, test-only.\n",
            "const TARGET_VECTORS: &[(&str, u32, &str)] = &[\n"]
    for number in sorted(values):
        # Zero is invalid block proof; preserve the helper's existing behavior
        # outside the valid nonzero target domain and explicitly test it below.
        work = (1 << 256) // (number + 1) if number else 0
        rows.append(f'    ("{number:064x}", 0x{compact(number):08x}, "{work:064x}"),\n')
    rows.append("];\nconst RETARGET_VECTORS: &[(u32, u32, u32, &str, u32)] = &[\n")
    times = [(0, 0), (1, 0), (1_000_000, 999_999), (2**32 - 1, 0),
             (0, 2**32 - 1), (2**32 - 1, 2**32 - 1)]
    times += [(1_000_000, 1_000_000 + span) for span in
              [1, 302399, 302400, 302401, 604800, 1209600, 2419200,
               4838399, 4838400, 4838401]]
    retargets = 0
    for bits in [0x01010000, 0x03008000, 0x1702c070, 0x1c00ffff, 0x1d00ffff]:
        for start, end in times:
            span = max(1_209_600 // 4, min(end - start, 1_209_600 * 4))
            new_target = min(target(bits) * span // 1_209_600, target(0x1d00ffff))
            rows.append(f'    ({start}, {end}, 0x{bits:08x}, "{new_target:064x}", 0x{compact(new_target):08x}),\n')
            retargets += 1
    rows.append("];\n")
    output = ROOT / "probe/src/vectors.rs"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("".join(rows))
    print(f"Generated {len(values)} target and {retargets} mainnet retarget vectors")


if __name__ == "__main__":
    main()
